import type { TargetLanguage } from './types';

/**
 * Format of one cache file (`_Translations/<note path>`). The file is a `.md`
 * note so Obsidian Sync transfers it without extra settings. Its body is a
 * one-line warning followed by plain JSON.
 *
 * Translations are stored in placeholder form (`⟦1⟧`), never with the
 * original links, tags or math restored. This keeps `[[links]]` and `#tags`
 * out of the cache note, so it never shows up in backlinks, the graph or the
 * tag pane. Placeholders are restored from the current original at render time.
 */

export const CACHE_VERSION = 2;

export const CACHE_WARNING =
	'Generated by the Transparent Translate plugin. This is a translation cache: do not edit it, changes are overwritten.';

export interface CacheEntry {
	/** Language of the original sentence, when known. */
	lang?: TargetLanguage | 'mixed';
	en?: string;
	de?: string;
	model?: string;
	translatedAt?: string;
	/**
	 * Fingerprint of the glossary entries that applied when each translation was
	 * made (absent: none applied). A different fingerprint now means the
	 * translation is outdated and is requested again.
	 */
	gl?: { en?: string; de?: string };
}

export interface ReplacedOriginal {
	at: string;
	/** Hash of the sentence that replaced the original, if any (null for deletions). */
	replacedWith: string | null;
	/** The previous sentence text on disk. */
	text: string;
}

export interface CacheFile {
	version: number;
	sentences: Record<string, CacheEntry>;
	replacedOriginals: ReplacedOriginal[];
}

export const MAX_REPLACED_ORIGINALS = 50;

export function emptyCache(): CacheFile {
	return { version: CACHE_VERSION, sentences: {}, replacedOriginals: [] };
}

export function serializeCache(cache: CacheFile): string {
	return `${CACHE_WARNING}\n\n${JSON.stringify(cache, null, '\t')}\n`;
}

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function sanitizeEntry(value: unknown): CacheEntry | null {
	if (!isRecord(value)) return null;
	const entry: CacheEntry = {};
	if (value.lang === 'en' || value.lang === 'de' || value.lang === 'mixed') entry.lang = value.lang;
	if (typeof value.en === 'string') entry.en = value.en;
	if (typeof value.de === 'string') entry.de = value.de;
	if (typeof value.model === 'string') entry.model = value.model;
	if (typeof value.translatedAt === 'string') entry.translatedAt = value.translatedAt;
	if (isRecord(value.gl)) {
		const gl: { en?: string; de?: string } = {};
		if (typeof value.gl.en === 'string') gl.en = value.gl.en;
		if (typeof value.gl.de === 'string') gl.de = value.gl.de;
		if (gl.en !== undefined || gl.de !== undefined) entry.gl = gl;
	}
	return entry;
}

/**
 * Parses a cache file. Never throws: anything unreadable yields an empty
 * cache, because the cache can always be regenerated.
 */
export function parseCache(content: string): CacheFile {
	const start = content.indexOf('{');
	if (start === -1) return emptyCache();
	let raw: unknown;
	try {
		raw = JSON.parse(content.slice(start));
	} catch {
		return emptyCache();
	}
	if (!isRecord(raw)) return emptyCache();

	const cache = emptyCache();
	if (isRecord(raw.sentences)) {
		for (const [hash, value] of Object.entries(raw.sentences)) {
			const entry = sanitizeEntry(value);
			if (entry && /^[0-9a-f]{64}$/.test(hash)) cache.sentences[hash] = entry;
		}
	}
	if (Array.isArray(raw.replacedOriginals)) {
		for (const item of raw.replacedOriginals) {
			if (!isRecord(item) || typeof item.text !== 'string' || typeof item.at !== 'string') continue;
			cache.replacedOriginals.push({
				at: item.at,
				text: item.text,
				replacedWith: typeof item.replacedWith === 'string' ? item.replacedWith : null,
			});
		}
	}
	return cache;
}

/** Records a replaced original, keeping only the newest entries. */
export function addReplacedOriginal(cache: CacheFile, item: ReplacedOriginal): void {
	cache.replacedOriginals.push(item);
	if (cache.replacedOriginals.length > MAX_REPLACED_ORIGINALS) {
		cache.replacedOriginals.splice(0, cache.replacedOriginals.length - MAX_REPLACED_ORIGINALS);
	}
}

/**
 * Removes entries whose hash is not in `live`. Entries translated less than
 * `keepDays` ago are kept, so undoing an edit does not cost a new request.
 * Returns the number of removed entries.
 */
export function pruneCache(cache: CacheFile, live: ReadonlySet<string>, now: Date, keepDays: number): number {
	const cutoff = now.getTime() - keepDays * 24 * 60 * 60 * 1000;
	let removed = 0;
	for (const [hash, entry] of Object.entries(cache.sentences)) {
		if (live.has(hash)) continue;
		const at = entry.translatedAt ? Date.parse(entry.translatedAt) : 0;
		if (Number.isFinite(at) && at > cutoff) continue;
		delete cache.sentences[hash];
		removed++;
	}
	return removed;
}
