import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin:
https://github.com/CodingJinxx/transparent-translate
*/
`;

const prod = process.argv[2] === 'production';

/**
 * Optional: set OBSIDIAN_PLUGIN_DIR to a vault's `.obsidian/plugins/transparent-translate`
 * folder and `npm run dev` copies every build there. Nothing is copied when it is unset.
 */
const devTarget = process.env.OBSIDIAN_PLUGIN_DIR;

/** @type {import('esbuild').Plugin} */
const copyToVault = {
	name: 'copy-to-vault',
	setup(build) {
		build.onEnd((result) => {
			if (!devTarget || result.errors.length > 0) return;
			if (!existsSync(devTarget)) mkdirSync(devTarget, { recursive: true });
			for (const file of ['main.js', 'manifest.json', 'styles.css']) {
				copyFileSync(file, join(devTarget, file));
			}
			console.log(`[copy-to-vault] copied build to ${devTarget}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	loader: { '.md': 'text' },
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: prod ? [] : [copyToVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
